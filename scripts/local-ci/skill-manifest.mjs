#!/usr/bin/env node
'use strict';

/**
 * skill-manifest.mjs — generate and verify `adws-pipeline/skill-manifest.json` (F-72).
 *
 * The manifest is a content digest of everything `install.sh` ships: every file under
 * `adws-pipeline/`, plus the ten `.claude/agents/adws-*.md` definitions that are installed
 * alongside it. It is what makes an installed copy self-describing — without it, an install
 * has no way to say which version of the skill it is, and nothing can tell a current install
 * from one that predates a security fix.
 *
 * That was F-72: all three installed copies were still pre-remediation and F-63/F-64/F-65
 * reproduced live in every one of them, while the repository's own gate was green. The
 * parity harness proves the validators in `git` are correct; it says nothing about the
 * validators that will actually run tomorrow.
 *
 * `skill_version` is derived from content, not from git. A commit hash would be
 * chicken-and-egg (writing the manifest changes the tree, which changes the commit) and
 * would go stale on a rebase or a cherry-pick; a content digest changes exactly when the
 * shipped bytes change, which is the property that matters. Git provenance is recorded
 * separately as advisory context and is explicitly NOT part of the version.
 *
 * Usage:
 *   node scripts/local-ci/skill-manifest.mjs --write   regenerate the manifest
 *   node scripts/local-ci/skill-manifest.mjs           verify it is current (gate step)
 *
 * Exit 0 when the manifest matches the tree; 1 when it is stale or missing.
 */

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');
const SKILL_DIR = path.join(ROOT, 'adws-pipeline');
const AGENTS_DIR = path.join(ROOT, '.claude', 'agents');
const MANIFEST_PATH = path.join(SKILL_DIR, 'skill-manifest.json');
const MANIFEST_NAME = 'skill-manifest.json';

const WRITE = process.argv.includes('--write');

function sha256(buf) {
  return crypto.createHash('sha256').update(buf).digest('hex');
}

/** Every file under dir, relative + POSIX-separated, sorted. */
function walk(dir, base = dir, acc = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(full, base, acc);
      continue;
    }
    // .DS_Store never ships (install.sh strips it), so it must not affect the version.
    if (entry.name === '.DS_Store') continue;
    // The manifest cannot contain its own hash.
    const rel = path.relative(base, full).split(path.sep).join('/');
    if (rel === MANIFEST_NAME) continue;
    acc.push(rel);
  }
  return acc;
}

function buildManifest() {
  const skillFiles = {};
  for (const rel of walk(SKILL_DIR)) {
    skillFiles[rel] = sha256(fs.readFileSync(path.join(SKILL_DIR, rel)));
  }

  const agentFiles = {};
  for (const name of fs.readdirSync(AGENTS_DIR).filter((f) => f.startsWith('adws-') && f.endsWith('.md')).sort()) {
    agentFiles[name] = sha256(fs.readFileSync(path.join(AGENTS_DIR, name)));
  }

  // The version is a digest OF the digests, so it changes exactly when shipped bytes do.
  const material = [
    ...Object.entries(skillFiles).map(([p, h]) => `skill/${p}:${h}`),
    ...Object.entries(agentFiles).map(([p, h]) => `agent/${p}:${h}`),
  ].join('\n');

  let gitCommit = null;
  try {
    gitCommit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch (_err) {
    /* a tarball export has no git; provenance is advisory */
  }

  return {
    _doc: [
      'Content digest of everything install.sh ships (F-72). Generated by',
      'scripts/local-ci/skill-manifest.mjs --write and asserted current by the same script',
      'in the Tier-1 gate, so a change to any shipped file without a regenerated manifest',
      'fails CI.',
      '',
      'skill_version is derived from CONTENT, not from git: a commit hash would be',
      'chicken-and-egg (writing this file changes the tree) and would go stale on a rebase.',
      'git_commit below is advisory provenance and is NOT part of the version.',
      '',
      'The installed copy carries this file, which is what lets scripts/skill-check.js',
      'verify an install against itself and `make check-installs` compare it to source.',
    ],
    skill_version: sha256(material).slice(0, 12),
    file_count: Object.keys(skillFiles).length + Object.keys(agentFiles).length,
    git_commit: gitCommit,
    skill: skillFiles,
    agents: agentFiles,
  };
}

const built = buildManifest();

if (WRITE) {
  // `git_commit` is advisory provenance and moves with HEAD, so rewriting unconditionally
  // would leave the manifest dirty after EVERY commit — a file that is always modified is
  // a file whose diffs stop being read. Rewrite only when the shipped content actually
  // changed; otherwise leave it byte-for-byte alone.
  const existing = fs.existsSync(MANIFEST_PATH) ? JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8')) : null;
  if (existing && existing.skill_version === built.skill_version) {
    console.log(
      `[skill-manifest] unchanged — version ${built.skill_version}, ${built.file_count} file(s); not rewritten`
    );
    process.exit(0);
  }
  fs.writeFileSync(MANIFEST_PATH, JSON.stringify(built, null, 2) + '\n');
  console.log(
    `[skill-manifest] wrote ${path.relative(ROOT, MANIFEST_PATH)} — version ${built.skill_version}, ${built.file_count} file(s)`
  );
  process.exit(0);
}

if (!fs.existsSync(MANIFEST_PATH)) {
  console.error('[skill-manifest] FAIL — no manifest. Run: node scripts/local-ci/skill-manifest.mjs --write');
  process.exit(1);
}

let onDisk;
try {
  onDisk = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
} catch (err) {
  console.error(`[skill-manifest] FAIL — manifest is not valid JSON: ${err.message}`);
  process.exit(1);
}

const problems = [];
if (onDisk.skill_version !== built.skill_version) {
  problems.push(
    `skill_version is ${onDisk.skill_version}, but the tree hashes to ${built.skill_version}`
  );
}
for (const section of ['skill', 'agents']) {
  const was = onDisk[section] || {};
  const now = built[section] || {};
  for (const p of Object.keys(now)) {
    if (!(p in was)) problems.push(`${section}/${p} is new and not in the manifest`);
    else if (was[p] !== now[p]) problems.push(`${section}/${p} changed since the manifest was written`);
  }
  for (const p of Object.keys(was)) {
    if (!(p in now)) problems.push(`${section}/${p} is in the manifest but no longer on disk`);
  }
}

if (problems.length) {
  console.error(`[skill-manifest] FAIL (${problems.length}) — the manifest is stale:`);
  for (const p of problems.slice(0, 12)) console.error(`  - ${p}`);
  if (problems.length > 12) console.error(`  … and ${problems.length - 12} more`);
  console.error('  Fix: node scripts/local-ci/skill-manifest.mjs --write (and commit it)');
  process.exit(1);
}

console.log(
  `[skill-manifest] OK — version ${built.skill_version}, ${built.file_count} shipped file(s) match the manifest`
);
